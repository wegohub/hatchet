#!/usr/bin/env python3
# 依据固定 NATS 依赖和 protobuf 字段生成静态转换；不生成动态 JSON 中转。
import json, pathlib, re, subprocess, os
root = pathlib.Path(__file__).resolve().parents[4]
extra = root / "internal/services/extra"
env = {**os.environ, "GOWORK": "off"}
module = json.loads(subprocess.check_output(
    ["go", "list", "-m", "-json", "github.com/nats-io/nats.go"], cwd=root, env=env
))
if module["Version"] != "v1.54.0":
    raise SystemExit("review field mappings before upgrading nats.go")
types = json.loads(subprocess.check_output(
    ["go", "run", str(extra / "scripts/types.go"), module["Dir"]], cwd=root, env=env
))

T={t['Name']:t for t in types if t['Package']=='jetstream' and t['Kind']=='struct'}
proto=(extra / 'proto/v1/extra.proto').read_text()
names=[n for n in T if re.search(r'message Nats'+n+r'\s*\{',proto)]

# 只生成请求配置需要的解码函数；响应信息只编码，避免重复无用途的镜像实现。
decode_names = {"StreamConfig", "ConsumerConfig", "KeyValueConfig"}
pending = list(decode_names)
while pending:
    name = pending.pop()
    for f in T[name]["Fields"] or []:
        dependency = f["Type"].replace("[]", "").lstrip("*")
        if dependency in T and dependency not in decode_names:
            decode_names.add(dependency)
            pending.append(dependency)

def snake(n):
 n=re.sub(r'([A-Z]+)([A-Z][a-z])',r'\1_\2',n)
 return re.sub(r'([a-z0-9])([A-Z])',r'\1_\2',n).lower()
def field(n):return ''.join(x[:1].upper()+x[1:] for x in snake(n).split('_'))
scalar={'string','bool','int','int32','int64','uint','uint8','uint16','uint32','uint64','float32','float64'}
def enc(ty,x):
 if ty.startswith('*'):
  tt=ty[1:];return f'mapPtr({x}, func(v {tt}) '+(' *pb.Nats'+tt if tt in T else '*timestamppb.Timestamp' if tt=='time.Time' else '*int64')+' { return '+(f'encode{tt}(&v)' if tt in T else 'stamp(v)' if tt=='time.Time' else f'ptr(int64(v))')+' })'
 if ty=='time.Time':return f'stamp({x})'
 if ty=='time.Duration':return f'ptr(int64({x}))'
 if ty=='nats.Header':return f'encodeHeaders({x})'
 if ty in ['[]string','[]uint64','[]byte']:return f'slices.Clone({x})'
 if ty.startswith('[]'):
  tt=ty[2:];resulttype='int64' if tt=='time.Duration' else '*pb.Nats'+tt.lstrip('*')
  f=f'int64(v)' if tt=='time.Duration' else f'encode{tt.lstrip("*")}(v)' if tt.startswith('*') else f'encode{tt}(&v)'
  return f'mapSlice({x}, func(v {tt}) {resulttype} {{ return {f} }})'
 if ty=='map[string]string' or ty=='map[string]uint64':return f'maps.Clone({x})'
 if ty in T:return f'encode{ty}(&{x})'
 if ty in ['int','int64']:return f'ptr(int64({x}))'
 if ty in ['uint8','uint16']:return f'ptr(uint32({x}))'
 if ty in scalar:return f'ptr({x})'
 if ty=='MigrationStatusType':return f'ptr(string({x}))'
 if ty=='StoreCompression':return f'ptr(uint32({x}))'
 return f'ptr(int64({x}))'
def dec(ty,x,pfield):
 if ty.startswith('*'):
  tt=ty[1:]
  if tt=='time.Time':return f'unstampPtr({pfield})'
  if tt in T:return f'decodePtr{tt}({pfield})'
  return f'mapPtr({pfield},func(v int64) *jetstream.{tt} {{ return ptr(jetstream.{tt}(v)) }})'
 if ty=='time.Time':return f'unstamp({x})'
 if ty=='time.Duration':return f'time.Duration({x})'
 if ty=='nats.Header':return f'decodeHeaders({x})'
 if ty in ['[]string','[]uint64','[]byte']:return f'slices.Clone({x})'
 if ty.startswith('[]'):
  tt=ty[2:]
  if tt=='time.Duration':return f'mapSlice({x},func(v int64) time.Duration {{ return time.Duration(v) }})'
  nt=tt.lstrip('*')
  return f'mapSlice({x},func(v *pb.Nats{nt}) '+('*' if tt.startswith('*') else '')+f'jetstream.{nt} {{ return '+(f'decodePtr{nt}(v)' if tt.startswith('*') else f'decode{nt}(v)')+' })'
 if ty.startswith('map['):return f'maps.Clone({x})'
 if ty in T:return f'decode{ty}({x})'
 if ty in scalar:return f'{ty}({x})'
 return f'jetstream.{ty}({x})'
out='''// Code generated by generate-convert.py; DO NOT EDIT.
// 静态字段转换避免消息链路经 JSON 或反射中转；配置校验在调用转换后统一完成。
package extra
import (
 "maps"
 "slices"
 "time"
 
 "github.com/nats-io/nats.go/jetstream"
 pb "github.com/hatchet-dev/hatchet/pkg/extra/v1"
 "google.golang.org/protobuf/types/known/timestamppb"
)
'''
for n in names:
 fs=T[n]['Fields'] or []
 out+=f'\n// encode{n} 将原生信息转换为独立协议快照，保留可选字段。\nfunc encode{n}(v *jetstream.{n}) *pb.Nats{n} {{\n if v==nil {{ return nil }}\n return &pb.Nats{n}{{\n'
 for f in fs:
  name=f['Name'] or f['Type'].lstrip('*');ty=f['Type'];pn=field(name)
  # 所有嵌套 NATS 类型显式限定包名。
  ex=enc(ty,'v.'+name)
  for tn in T:ex=re.sub(r'(?<![.\w])'+re.escape(tn)+r'\b', 'jetstream.'+tn,ex)
  for tn in ['RetentionPolicy']:ex=re.sub(r'(?<![.\w])'+tn+r'\b','jetstream.'+tn,ex)
  out+=f' {pn}: {ex},\n'
 out+=' }\n}\n'
 if n in decode_names:
  out+=f'\n// decode{n} 将已验证请求转换为原生配置，所有容器独立复制。\nfunc decode{n}(p *pb.Nats{n}) jetstream.{n} {{\n if p==nil {{ return jetstream.{n}{{}} }}\n return jetstream.{n}{{\n'
  for f in fs:
   name=f['Name'] or f['Type'].lstrip('*');ty=f['Type'];pn=field(name)
   out+=f' {name}: '+dec(ty,'p.Get'+pn+'()','p.'+pn)+',\n'
  out+=' }\n}\n'
  out+=f'\n// decodePtr{n} 保留未指定的 nil 状态，不用空配置替代。\nfunc decodePtr{n}(p *pb.Nats{n}) *jetstream.{n} {{\n if p==nil {{return nil}}\n v:=decode{n}(p)\n return &v\n}}\n'
(pathlib.Path(os.environ.get('EXTRA_GENERATE_OUTPUT',str(extra))) / 'convert_generated.go').write_text(out)
print('converted',len(names))
subprocess.run(["gofmt","-w",str(pathlib.Path(os.environ.get("EXTRA_GENERATE_OUTPUT",str(extra))) / "convert_generated.go")],check=True)
